// bundle-sim.mjs — produce site/vendor.mjs: the REAL src/crdt.mjs + src/macp.mjs
// kernels, rewritten to run in the browser (tiny shims replace node:crypto/fs/path).
// Rerun whenever src/crdt.mjs or src/macp.mjs changes; publish-check verifies drift.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(ROOT, p), 'utf8');

const SHIM = `// — browser shims (generated by scripts/bundle-sim.mjs; do not edit by hand) —
const createHash = (() => {
  const shake = (prev, s) => { let h = prev; for (let i = 0; i < s.length; i++) { h = ((h << 5) - h + s.charCodeAt(i)) | 0; h = (h ^ (h >>> 13)) | 0; } return h; };
  return (algo = 'sha256') => { let s = ''; return {
    update(x) { s += typeof x === 'string' ? x : String(x); return this; },
    digest(enc) { let h1 = 0x2f6e2b1 ^ s.length, h2 = 0x7ab9d3; for (let i = 0; i < s.length; i += 19) { h1 = shake(h1, s.slice(i, i + 19)); h2 = shake(h2, s.slice(i + 7, i + 19)); } const hex = (n) => (n >>> 0).toString(16).padStart(8, '0'); const out = hex(h1) + hex(h2) + hex(h1 ^ h2) + hex(h2 << 3 | s.length); return enc?.includes('hex') || enc === undefined ? out : out.split('').map((c) => String.fromCharCode(parseInt(c, 16))).join(''); },
  }; };
})();
const existsSync = () => false;
const readFileSync = () => { throw new Error('vendor shim: no fs in browser (persistence is optional in MACP)'); };
const writeFileSync = () => {}; // persistence optional; could localStorage later
const join = (...p) => p.filter(Boolean).join('/');
`;

let crdt = read('src/crdt.mjs');
let macp = read('src/macp.mjs');
// strip ONLY the node imports we shim; keep every other line byte-identical
crdt = crdt.replace(/^import .*$/gm, (m) => (m.includes('node:') ? '' : m)); // crdt has none today, future-proof
macp = macp.replace(/^import .*(?:node:crypto|node:fs|node:path).*$/gm, '');
macp = macp.replace(/import \{ createHash.*?;\n?/s, '').replace(/import \{.*?node:fs.*?\};\n?/s, '').replace(/import \{ join.*?\};\n?/s, '');
const header = `// site/vendor.mjs — GENERATED by scripts/bundle-sim.mjs from the REAL kernels:
//   src/crdt.mjs (SemanticDocument / Lamport LWW CRDT)
//   src/macp.mjs (MACP 5-mode quorum kernel)
// Rewritten for the browser with tiny shims. Do not edit; regenerate instead.
${SHIM}\n`;
const out = `${header}/* ===== src/crdt.mjs (verbatim body) ===== */\n${crdt.trimStart()}\n/* ===== src/macp.mjs (verbatim body) ===== */\n${macp.trimStart()}\n`;
const dest = join(ROOT, 'site', 'vendor.mjs');
writeFileSync(dest, out);
console.log(`vendor.mjs written (${out.length} bytes).`);
