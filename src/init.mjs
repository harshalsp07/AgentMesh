// init.mjs — P0: install AgentMesh into ANY repo in 60 seconds. TTFC is everything:
// this writes agent config without asking the user which IDE they use — we detect.
// Usage: mesh init [targetRoot] [--hub <url>] [--actor <name>] [--force]
// Writes: .agents/mcp_config.json (Antigravity), .agents/rules/agentmesh.md (rules),
//         plus (into EXISTING files unless --force): .mcp.json (Claude Code),
//         .cursor/mcp.json, .windsurf/mcp_config.json, opencode.json (OpenCode).
//         Codex/Grok get instructions via AGENTS.md + printed instructions.
import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, resolve, basename } from 'node:path';

const SERVER_ENTRY = ({ actor, hub, token }) => ({
  command: 'npx',
  args: ['-y', '@harshalsp/agentmesh', 'bridge'],
  // MESH_TOKEN is required once the hub enforces capability auth (`mesh up`
  // creates the keys). Without it every MCP tool call fails with 401.
  env: { MESH_ACTOR: actor, MESH_HUB: hub, ...(token ? { MESH_TOKEN: token } : {}) },
});

export const CLIENTS = [
  { id: 'antigravity', name: 'Google Antigravity', file: () => join('.agents', 'mcp_config.json'), key: 'mcpServers', required: true },
  { id: 'claude-code', name: 'Claude Code', file: () => '.mcp.json', key: 'mcpServers' },
  { id: 'cursor', name: 'Cursor', file: () => join('.cursor', 'mcp.json'), key: 'mcpServers' },
  { id: 'windsurf', name: 'Windsurf', file: () => join('.windsurf', 'mcp_config.json'), key: 'mcpServers' },
  { id: 'opencode', name: 'OpenCode', file: () => 'opencode.json', key: 'mcp' },
  { id: 'codex', name: 'Codex CLI', file: () => join('.codex', 'config.toml'), key: null }, // TOML: instructions only
];

function writeJson(p, o) {
  const parent = p.slice(0, Math.max(p.lastIndexOf('/'), p.lastIndexOf('\\')));
  if (parent) mkdirSync(parent, { recursive: true });
  writeFileSync(p, JSON.stringify(o, null, 2) + '\n');
}
// upsert the `agentmesh` server entry under the client's canonical server map.
// Empty/new docs are seeded as {mcpServers:{agentmesh}} (the common MCP shape);
// existing maps (mcpServers / mcp / root) are respected and never clobbered.
function upsertServers(p, entry, key = 'mcpServers') {
  let doc = {};
  try { doc = JSON.parse(readFileSync(p, 'utf8')); } catch {}
  const root = doc && typeof doc === 'object' && !Array.isArray(doc) ? doc : {};
  let container = root;
  let usedKey = null;
  for (const cand of [key, 'mcpServers', 'mcp']) {
    if (root[cand] && typeof root[cand] === 'object' && !Array.isArray(root[cand])) { container = root[cand]; usedKey = cand; break; }
  }
  if (!usedKey) { container = root[key] = {}; usedKey = key; }
  container.agentmesh = { ...entry, ...(container.agentmesh || {}) };
  root[usedKey] = container;
  writeJson(p, root);
  return root;
}

export function deriveActor(targetRoot) {
  try {
    const pkg = JSON.parse(readFileSync(join(targetRoot, 'package.json'), 'utf8'));
    if (pkg.name) return `${String(pkg.name).replace(/^@[^/]+\//, '').replace(/[^a-zA-Z0-9-]/g, '-').slice(0, 32)}-agent`;
  } catch {}
  return `${basename(resolve(targetRoot)).replace(/[^a-zA-Z0-9-]/g, '-').slice(0, 32)}-agent`;
}

const RULES_MD = `# AgentMesh rules (auto-generated by \`mesh init\`)

You are a peer agent on a shared repo. Follow the mesh protocol — it is cheap:

1. **Declare before you edit.** Call \`mesh_declare_intent\` with your goal and globs
   BEFORE writing files. Collisions are forecast before they exist.
2. **One lane per actor.** Your lane snapshots every turn (\`mesh snapshot <you>\`).
   \`mesh undo / mesh rewind <you>\` always recover the last state.
3. **Contracts are machine-read.** If you change an API/route/schema, the mesh
   notifies every consumer before your code lands. Keep changes non-breaking
   unless a quorum window is open (\`mesh_propose_contract\`).
4. **Trunk is protected.** Never merge to main yourself: queue via the mesh; the
   verification harness decides.
5. **Message peers via the mesh**, not by editing their files.
   \`mesh_request to:@<actor> text:"..."\` is the inbox channel.
6. If the hub is down, ignore the mesh gracefully and keep working: the repo
   remains an ordinary git repo. Recovery is automatic.
`;

export function init(targetRoot, { hub = 'http://localhost:7777', actor = null, force = false, token = null } = {}) {
  const out = { ok: true, targetRoot, files: [], detected: [], skipped: [], next: [] };
  actor = actor && String(actor).trim() ? String(actor).trim() : deriveActor(targetRoot);
  const entry = SERVER_ENTRY({ actor, hub: hub.replace(/\/$/, ''), token: token || process.env.MESH_TOKEN || null });

  // 1) rules live inside the target repo so every harness reads them natively
  const rulesDir = join(targetRoot, '.agents', 'rules');
  mkdirSync(rulesDir, { recursive: true });
  writeFileSync(join(rulesDir, 'agentmesh.md'), RULES_MD);
  out.files.push('.agents/rules/agentmesh.md');

  // 2) every known client: antigravity always; others only where a config already
  //    exists (never invent configs for IDEs the team does not use — cheap discovery)
  for (const c of CLIENTS) {
    if (c.id === 'codex') { out.skipped.push({ client: c.id, why: 'shares one global ~/.codex/config.toml — print instructions instead' }); continue; }
    const p = join(targetRoot, c.file());
    const exists = existsSync(p);
    if (!exists && !force && !c.required) {
      out.skipped.push({ client: c.id, why: `${c.file()} absent (pass --force to create)` });
      continue;
    }
    upsertServers(p, entry, c.key);
    out.files.push(c.file().replaceAll('\\', '/'));
    out.detected.push(c.id);
  }

  // 3) AGENTS.md hookup — every harness (incl. Grok Build) reads it; keep it additive
  const agents = join(targetRoot, 'AGENTS.md');
  if (!existsSync(agents)) {
    writeFileSync(agents, `# ${basename(resolve(targetRoot))} — agent rules\n\n## AgentMesh\n\nMultiple agents collaborate here under coordination: declare intents with \`mesh_declare_intent\` before editing; see .agents/rules/agentmesh.md.\n`);
    out.files.push('AGENTS.md');
  } else {
    let md = readFileSync(agents, 'utf8');
    if (!/agentmesh/i.test(md)) {
      md += '\n## AgentMesh\n\nMultiple agents work here under coordination: declare intents with `mesh_declare_intent` before editing; see .agents/rules/agentmesh.md.\n';
      writeFileSync(agents, md);
      out.files.push('AGENTS.md');
    }
  }

  out.actor = actor;
  out.next = [
    `@${actor} is configured. Verify connectivity: mesh doctor`,
    `Join a running hub: node bin/mesh-join ${hub}`,
    `Or start a hub on this machine: node src/hub.mjs (MESH_HOST=0.0.0.0 for LAN)`,
  ];
  return out;
}

export function doctorFix(targetRoot, { hub = 'http://localhost:7777' } = {}) {
  const r = init(targetRoot, { hub, force: false });
  return { ok: true, fixed: r.files, detected: r.detected, skipped: r.skipped, note: 'idempotent: existing agentmesh entries preserved' };
}
