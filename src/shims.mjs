// shims.mjs — boundary enforcement that actually executes. `mesh run --lane X -- <cmd>`
// spawns with PATH=<shimDir>:$PATH so package managers / git / rm / terraform go
// through policy first: deny -> refuse (exit 126, real binary never runs);
// require_approval without MESH_APPROVED=1 -> refuse (exit 125); else exec through.
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, writeFileSync, accessSync, constants } from 'node:fs';
import { join, delimiter } from 'node:path';
import { loadPolicy, checkCommand } from './policy.mjs';

export const SHIMMED = ['npm', 'pnpm', 'yarn', 'pip', 'pip3', 'uv', 'cargo', 'go', 'git', 'rm', 'terraform', 'docker'];
const shimDir = (root) => join(root, 'shims');

export function buildShims(root, meshSrcDir) {
  const dir = shimDir(root);
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, 'package.json'), JSON.stringify({ type: 'module' }));
  for (const bin of SHIMMED) {
    writeFileSync(join(dir, bin), `#!/usr/bin/env node
// generated by mesh — do not edit. Policy gate for '${bin}'.
import { spawnSync } from 'node:child_process';
import path from 'node:path';
import fs from 'node:fs';
const { loadPolicy, checkCommand } = await import(${JSON.stringify('file://' + join(meshSrcDir, 'policy.mjs'))});
const policy = loadPolicy(${JSON.stringify(root)});
const cmdline = [${JSON.stringify(bin)}, ...process.argv.slice(2)].join(' ');
const v = checkCommand(policy, cmdline);
if (v.verdict === 'deny') { console.error(JSON.stringify({ ok: false, tier: 0, ...v })); process.exit(126); }
if (v.verdict === 'approval' && process.env.MESH_APPROVED !== '1') { console.error(JSON.stringify({ ok: false, ...v, hint: 're-run with MESH_APPROVED=1 after human review' })); process.exit(125); }
const paths = (process.env.PATH || '').split(path.delimiter).filter((p) => p !== ${JSON.stringify(dir)});
let real = null;
for (const p of paths) { try { fs.accessSync(path.join(p, ${JSON.stringify(bin)}), fs.constants.X_OK); real = path.join(p, ${JSON.stringify(bin)}); break; } catch {} }
if (!real) { console.error(JSON.stringify({ ok: false, error: 'real binary not found on PATH: ${bin}' })); process.exit(127); }
const r = spawnSync(real, process.argv.slice(2), { stdio: 'inherit' });
process.exit(r.status ?? 1);
`, { mode: 0o755 });
  }
  return { ok: true, dir, bins: SHIMMED };
}
// pre-flight decision without executing (for dry runs + tests)
export const decide = (root, cmdline) => checkCommand(loadPolicy(root), cmdline);
// real L4 wrap: policy pre-check, then spawn inside the lane with shimmed PATH
export function runWrapped(root, lane, cmd, argv = [], { timeout = 120000 } = {}) {
  const pre = decide(root, [cmd, ...argv].join(' '));
  if (pre.verdict === 'deny') return { ok: false, tier: 0, code: 126, ...pre, note: 'refused before exec; real binary never ran' };
  if (pre.verdict === 'approval' && process.env.MESH_APPROVED !== '1') return { ok: false, code: 125, ...pre };
  const { dir } = buildShims(root, new URL('.', import.meta.url).pathname);
  const laneDir = join(root, 'lanes', lane);
  mkdirSync(laneDir, { recursive: true });
  const env = {
    ...process.env,
    PATH: dir + delimiter + (process.env.PATH || ''),
    MESH_LANE: lane, MESH_DIR: root,
  };
  const r = spawnSync(cmd, argv, { cwd: laneDir, env, timeout, encoding: 'utf8', maxBuffer: 16 * 1024 * 1024 });
  return { ok: (r.status ?? 1) === 0, code: r.status ?? 1, stdout: (r.stdout || '').slice(-4000), stderr: (r.stderr || '').slice(-2000), lane };
}
export const shimPresent = (root, bin) => {
  try { accessSync(join(shimDir(root), bin), constants.X_OK); return true; } catch { return false; }
};
